#!/usr/bin/env python3
"""Pack the WHATWG Encoding Standard indexes into crates/seagent-channel/data/ for charset.rs.

Usage (download into a fresh empty directory first; the inputs are data, never executed):
    mkdir /tmp/whatwg && cd /tmp/whatwg
    for f in big5 gb18030 gb18030-ranges jis0208 jis0212 euc-kr ibm866 iso-8859-2 ... ; do
        curl -fO https://encoding.spec.whatwg.org/index-$f.txt; done
    curl -fO https://encoding.spec.whatwg.org/encodings.json
    python3 -I tools/gen_charset_tables.py /tmp/whatwg crates/seagent-channel/data

Outputs (all little-endian):
    <name>.bin       u16 first pointer, u16 count, count × u16 code point (0 = unmapped)
                     for big5, gb18030, jis0208, jis0212, euc-kr; big5.bin is followed by a
                     bitmap (bit i set = pointer first+i is U+2xxxx, the u16 holds the low bits)
    gb18030-ranges.bin   (u32 pointer, u32 code point) pairs, sorted
    single-byte.bin  128 × u16 (bytes 0x80..0xFF) per single-byte encoding, in the order of
                     SINGLE below (charset.rs keeps the same order)
    labels.txt       `Name label label…` per encoding, from encodings.json
"""
import json
import os
import struct
import sys

SINGLE = ["IBM866", "ISO-8859-2", "ISO-8859-3", "ISO-8859-4", "ISO-8859-5", "ISO-8859-6", "ISO-8859-7", "ISO-8859-8", "ISO-8859-10", "ISO-8859-13", "ISO-8859-14", "ISO-8859-15", "ISO-8859-16", "KOI8-R", "KOI8-U", "macintosh", "windows-874", "windows-1250", "windows-1251", "windows-1252", "windows-1253", "windows-1254", "windows-1255", "windows-1256", "windows-1257", "windows-1258", "x-mac-cyrillic"]
MULTI = ["big5", "gb18030", "jis0208", "jis0212", "euc-kr"]


def read_index(src, name):
    out, ident = {}, ""
    with open(os.path.join(src, f"index-{name}.txt"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("# Identifier:"):
                ident = line.split(":", 1)[1].strip()
            line = line.split("#", 1)[0].split()
            if len(line) >= 2:
                p, cp = int(line[0]), int(line[1], 16)
                assert p not in out and 0 < cp <= 0x10FFFF, (name, p)
                out[p] = cp
    return out, ident


def main(src, dst):
    idents, total = [], 0

    def write(fname, data):
        nonlocal total
        with open(os.path.join(dst, fname), "wb") as f:
            f.write(data)
        total += len(data)
        print(f"{fname}: {len(data)} bytes")

    for name in MULTI:
        idx, ident = read_index(src, name)
        idents.append(f"index-{name} {ident}")
        lo, hi = min(idx), max(idx)
        n = hi - lo + 1
        vals, astral = [], bytearray((n + 7) // 8)
        for i in range(n):
            cp = idx.get(lo + i, 0)
            if cp > 0xFFFF:
                assert name == "big5" and cp >> 16 == 2 and cp & 0xFFFF, (name, cp)
                astral[i // 8] |= 1 << (i % 8)
            vals.append(cp & 0xFFFF)
        data = struct.pack(f"<HH{n}H", lo, n, *vals)
        write(f"{name}.bin", data + (bytes(astral) if name == "big5" else b""))
    ranges, ident = read_index(src, "gb18030-ranges")
    idents.append(f"index-gb18030-ranges {ident}")
    write("gb18030-ranges.bin", b"".join(struct.pack("<II", p, ranges[p]) for p in sorted(ranges)))
    sb = b""
    for name in SINGLE:
        idx, ident = read_index(src, name.lower())
        idents.append(f"index-{name.lower()} {ident}")
        assert all(0 <= p < 128 and idx[p] <= 0xFFFF for p in idx), name
        sb += struct.pack("<128H", *[idx.get(p, 0) for p in range(128)])
    write("single-byte.bin", sb)

    with open(os.path.join(src, "encodings.json"), encoding="utf-8") as f:
        groups = json.load(f)
    lines, squashed = [], {}
    for g in groups:
        for e in g["encodings"]:
            for lab in e["labels"]:
                assert lab == lab.lower() and " " not in lab, lab
                k = "".join(c for c in lab if c.isalnum())
                # charset.rs retries with separators removed; that must stay unambiguous.
                assert squashed.setdefault(k, e["name"]) == e["name"], (lab, e["name"])
            lines.append(" ".join([e["name"]] + e["labels"]))
    head = ["# WHATWG Encoding Standard labels (encodings.json) and index identifiers.", "# Generated by tools/gen_charset_tables.py; do not edit."]
    write("labels.txt", ("\n".join(head + [f"# {i}" for i in idents] + lines) + "\n").encode())
    print(f"total: {total} bytes")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
